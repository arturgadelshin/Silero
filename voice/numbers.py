#!/usr/bin/env python3
"""numbers.py — числа словами для Silero: в его алфавите цифр нет.

RUAccent числа не раскрывает, а `num2words` в образе нет, поэтому здесь свой
компактный раскрыватель. Что умеет:

  15:30            -> пятнадцать тридцать      (время, минуты < 10 с «ноль»)
  1-й, 25-го, 3-я  -> первый, двадцать пятого, третья  (порядковые с окончанием)
  +12, -5          -> плюс двенадцать, минус пять
  3,5              -> три целых пять десятых   (одна-две цифры после запятой)
  4815             -> четыре тысячи восемьсот пятнадцать
  89161234567      -> по цифрам (длинные числа — это коды и телефоны)

Чего не умеет и не притворяется: род определяется не по соседнему слову, а по
умолчанию мужской («два подъезда», но «два квартиры» — тоже «два»). Исключение
одно: тысячи всегда женского рода («одна тысяча», «две тысячи»). Если нужен
другой род, проще написать слово в тексте руками.
"""
import re

UNITS_M = ["ноль", "один", "два", "три", "четыре", "пять", "шесть", "семь",
           "восемь", "девять"]
UNITS_F = {1: "одна", 2: "две"}
TEENS = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
         "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"]
TENS = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят",
        "семьдесят", "восемьдесят", "девяносто"]
HUNDREDS = ["", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот",
            "семьсот", "восемьсот", "девятьсот"]
# (единственное, 2-4, 5+) для согласования с числом
SCALES = [None, ("тысяча", "тысячи", "тысяч"), ("миллион", "миллиона", "миллионов"),
          ("миллиард", "миллиарда", "миллиардов")]

ORD_UNITS = ["нулевой", "первый", "второй", "третий", "четвёртый", "пятый",
             "шестой", "седьмой", "восьмой", "девятый"]
ORD_TEENS = ["десятый", "одиннадцатый", "двенадцатый", "тринадцатый",
             "четырнадцатый", "пятнадцатый", "шестнадцатый", "семнадцатый",
             "восемнадцатый", "девятнадцатый"]
ORD_TENS = ["", "", "двадцатый", "тридцатый", "сороковой", "пятидесятый",
            "шестидесятый", "семидесятый", "восьмидесятый", "девяностый"]
ORD_HUND = ["", "сотый", "двухсотый", "трёхсотый", "четырёхсотый", "пятисотый",
            "шестисотый", "семисотый", "восьмисотый", "девятисотый"]
FRACTION = {1: ("десятая", "десятых"), 2: ("сотая", "сотых")}


def _trio(n, fem=False):
    """сотни-десятки-единицы одной группы"""
    out = []
    if n >= 100:
        out.append(HUNDREDS[n // 100])
        n %= 100
    if 10 <= n <= 19:
        out.append(TEENS[n - 10])
    else:
        if n >= 20:
            out.append(TENS[n // 10])
            n %= 10
        if n:
            out.append(UNITS_F[n] if fem and n in UNITS_F else UNITS_M[n])
    return out


def _plural(n, forms):
    """тысяча / тысячи / тысяч по последним цифрам"""
    n1, n2 = n % 10, n % 100
    if 11 <= n2 <= 14 or n1 == 0 or n1 >= 5:
        return forms[2]
    return forms[0] if n1 == 1 else forms[1]


def cardinal(n):
    if n < 0:
        return "минус " + cardinal(-n)
    if n == 0:
        return "ноль"
    groups = []
    while n:
        groups.append(n % 1000)
        n //= 1000
    out = []
    for k in range(len(groups) - 1, -1, -1):
        g = groups[k]
        if not g:
            continue
        out += _trio(g, fem=(k == 1))
        if k:
            out.append(_plural(g, SCALES[k]))
    return " ".join(out)


def ordinal(n, suffix="й"):
    """порядковое: последняя значащая часть склоняется, остальное — количественное"""
    if n <= 0 or n > 999:
        return cardinal(n)
    head, last = [], ""
    h, t, u = n // 100, (n % 100) // 10, n % 10
    if 10 <= n % 100 <= 19:
        last = ORD_TEENS[n % 100 - 10]
        if h:
            head.append(HUNDREDS[h])
    elif u:
        last = ORD_UNITS[u]
        if h:
            head.append(HUNDREDS[h])
        if t:
            head.append(TENS[t])
    elif t:
        last = ORD_TENS[t]
        if h:
            head.append(HUNDREDS[h])
    else:
        last = ORD_HUND[h]
    return " ".join(head + [_decline(last, suffix)])


def _decline(word, suffix):
    """окончание берём из самого текста: «1-й» мужской, «3-я» женский, «25-го» родительный"""
    stem, end = word[:-2], word[-2:]
    soft = end == "ий"                                  # третий
    table = {
        "й": ("ый", "ой", "ий"), "я": ("ая", "ая", "ья"), "е": ("ое", "ое", "ье"),
        "ое": ("ое", "ое", "ье"), "ая": ("ая", "ая", "ья"), "ый": ("ый", "ой", "ий"),
        "го": ("ого", "ого", "ьего"), "ого": ("ого", "ого", "ьего"),
        "ом": ("ом", "ом", "ьем"), "м": ("ым", "ым", "ьим"), "му": ("ому", "ому", "ьему"),
        "ю": ("ую", "ую", "ью"), "ую": ("ую", "ую", "ью"), "х": ("ых", "ых", "ьих"),
        "ых": ("ых", "ых", "ьих"), "её": ("ые", "ые", "ьи"), "и": ("ые", "ые", "ьи"),
    }
    v = table.get(suffix)
    if not v:
        return word
    if soft:
        return stem + v[2]
    return stem + (v[1] if end == "ой" else v[0])


def _time(m):
    h, mi = int(m.group(1)), int(m.group(2))
    if h > 23 or mi > 59:
        return m.group(0)
    s = cardinal(h)
    if mi == 0:
        return s + " ноль ноль"
    return s + (" ноль " if mi < 10 else " ") + cardinal(mi)


def _decimal(m):
    whole, frac = int(m.group(1)), m.group(2)
    k = len(frac)
    if k > 2:
        return m.group(0)
    forms = FRACTION[k]
    n = int(frac)
    w = "целая" if whole % 10 == 1 and whole % 100 != 11 else "целых"
    tail = forms[0] if n % 10 == 1 and n % 100 != 11 else forms[1]
    return f"{' '.join(_trio(whole % 1000, fem=True)) if whole < 1000 else cardinal(whole)} " \
           f"{w} {' '.join(_trio(n, fem=True))} {tail}"


def _plain(m):
    s = m.group(0)
    if len(s) > 6:                                     # коды и телефоны — по цифрам
        return " ".join(UNITS_M[int(c)] for c in s)
    return cardinal(int(s))


def expand(text):
    t = re.sub(r"\b(\d{1,2}):(\d{2})\b", _time, text)
    t = re.sub(r"(\d+)-([а-яё]{1,3})\b",
               lambda m: ordinal(int(m.group(1)), m.group(2)), t)
    t = re.sub(r"(?<![\w.,])([+−-])\s?(\d)",
               lambda m: ("плюс " if m.group(1) == "+" else "минус ") + m.group(2), t)
    t = re.sub(r"\b(\d+)[.,](\d+)\b", _decimal, t)
    t = re.sub(r"\d+", _plain, t)
    return re.sub(r"\s+", " ", t)


if __name__ == "__main__":
    import sys
    for line in (sys.argv[1:] or [
            "Спуститесь на 1-й этаж.", "Сейчас 15:30, на улице +12 градусов.",
            "В доме 25 квартир и 3 подъезда.", "Код 4815 придёт в чат.",
            "Позвони на 89161234567.", "Осталось 3,5 часа до 7:05.",
            "Это 2-я попытка 21-го числа, 101-й раз."]):
        print(line, "->", expand(line))
