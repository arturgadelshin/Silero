"""Числа словами. В алфавите Silero цифр нет: всё, что не раскрылось,
молча пропадёт из речи, поэтому главная проверка — цифр не осталось.
"""
import re

import pytest

from voice.numbers import expand

CASES = [
    ("Спуститесь на 1-й этаж.", "Спуститесь на первый этаж."),
    ("Сейчас 15:30.", "Сейчас пятнадцать тридцать."),
    ("До 7:05 осталось немного.", "До семь ноль пять осталось немного."),
    ("На улице +12 градусов.", "На улице плюс двенадцать градусов."),
    ("Температура -5 ночью.", "Температура минус пять ночью."),
    ("Осталось 3,5 часа.", "Осталось три целых пять десятых часа."),
    ("Код 4815 придёт в чат.", "Код четыре тысячи восемьсот пятнадцать придёт в чат."),
    ("Это 2-я попытка 21-го числа.", "Это вторая попытка двадцать первого числа."),
    ("Подъездов 3-я штука.", "Подъездов третья штука."),
]


@pytest.mark.parametrize("src,want", CASES)
def test_expand(src, want):
    assert expand(src) == want


@pytest.mark.parametrize("src", [c[0] for c in CASES] + [
    "Позвони на 89161234567.", "В доме 25 квартир и 3 подъезда.",
    "Дом 1, корпус 2, квартира 345.", "0 градусов и 100 процентов.",
])
def test_no_digits_left(src):
    assert not re.search(r"\d", expand(src))


def test_long_number_is_read_by_digits():
    out = expand("89161234567")
    assert out.split()[0] == "восемь"
    assert "тысяч" not in out


def test_thousands_are_feminine():
    assert "одна тысяча" in expand("1000")
    assert "две тысячи" in expand("2000")
